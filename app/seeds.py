ACCOUNT_SUFFIXES = ("个人号", "企业号", "机构号", "官方号", "官方")


def guess_account_type(name):
    """按平台名判断是官方号还是个人号；新建平台时用它给默认值。"""
    n = name or ""
    if any(k in n for k in ("企业号", "机构号", "官方", "企业")):
        return "official"
    return "personal"


def split_platform_name(name):
    """把「抖音企业号」拆成 ("抖音", "official")。

    平台名只管平台本体，官方号 / 个人号由 account_type 单独表达。
    名称里没带可识别的后缀时原样返回，第二项返回 None（表示"用户没指定，
    按平台默认走"），这样老数据升级和新平台录入可以共用一套逻辑。
    """
    n = (name or "").strip()
    for suf in ACCOUNT_SUFFIXES:
        if n.endswith(suf) and len(n) > len(suf):
            at = "personal" if suf == "个人号" else "official"
            return n[: -len(suf)].strip(), at
    return n, None


